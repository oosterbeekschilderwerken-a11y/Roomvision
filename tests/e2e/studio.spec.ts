import { test, expect } from '@playwright/test';
import path from 'node:path';
const photo = path.resolve('public/demo-panorama.jpg');
test('homepage links to an actual rendered WebGL panorama; drag, zoom, reset, upload and errors work', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (e) => errors.push(e.message));
  await page.goto('/');
  await expect(page).toHaveTitle(/RoomVision/);
  await page.getByRole('link', { name: /Ontdek de 360° studio/ }).click();
  await expect(page.getByText('Panorama laden…')).toHaveCount(0);
  const canvas = page.locator('canvas');
  await expect(canvas).toBeVisible();
  expect(await canvas.evaluate((c: HTMLCanvasElement) => !!(c.getContext('webgl2') || c.getContext('webgl')))).toBe(true);
  const initial = await canvas.screenshot();
  const box = (await canvas.boundingBox())!;
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width / 2 + 140, box.y + box.height / 2 + 40, { steps: 12 });
  await page.mouse.up();
  const dragged = await canvas.screenshot();
  expect(dragged.equals(initial)).toBe(false);
  await page.getByRole('button', { name: 'Inzoomen', exact: true }).click();
  await expect(page.getByText('115%', { exact: true })).toBeVisible();
  expect((await canvas.screenshot()).equals(dragged)).toBe(false);
  await page.getByRole('button', { name: 'Weergave herstellen' }).click();
  await expect(page.getByText('100%', { exact: true })).toBeVisible();
  await page.getByRole('region', { name: /Interactieve/ }).focus();
  await page.keyboard.press('ArrowLeft');
  expect((await canvas.screenshot()).equals(initial)).toBe(false);
  await page.locator('input[type=file]').setInputFiles({ name: 'bestand.txt', mimeType: 'text/plain', buffer: Buffer.from('invalid') });
  await expect(page.locator('.upload-error, .viewer-message.error')).toContainText('bestandstype');
  await page.locator('input[type=file]').setInputFiles({ name: 'kapot.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('invalid') });
  await expect(page.locator('.upload-error, .viewer-message.error')).toContainText('geen leesbare foto');
  const square = await page.evaluate(async () => {
    const c = document.createElement('canvas'); c.width = c.height = 1024;
    return c.toDataURL('image/png').split(',')[1];
  });
  await page.locator('input[type=file]').setInputFiles({ name: 'vierkant.png', mimeType: 'image/png', buffer: Buffer.from(square, 'base64') });
  await expect(page.locator('.upload-error, .viewer-message.error')).toContainText('verhouding');
  await page.locator('input[type=file]').setInputFiles(photo);
  await expect(page.getByText('demo-panorama.jpg', { exact: true })).toBeVisible();
  await expect(page.getByText('Panorama laden…')).toHaveCount(0);
  await expect(page.locator('.upload-error, .viewer-message.error')).toHaveCount(0);
  await page.getByRole('button', { name: /Open het voorbeeldpanorama/ }).click();
  await expect(page.getByText('Voorbeeld · buitenpanorama')).toBeVisible();
  await expect(page.getByText('Panorama laden…')).toHaveCount(0);
  expect(errors).toEqual([]);
});
test('mobile layout fits and supports touch drag and pinch zoom', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 });
  const page = await context.newPage();
  await page.goto('/studio');
  await expect(page.getByText('Panorama laden…')).toHaveCount(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const canvas = page.locator('canvas');
  const before = await canvas.screenshot();
  const box = (await canvas.boundingBox())!;
  const x = box.x + box.width / 2, y = box.y + box.height / 2;
  const session = await context.newCDPSession(page);
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y }] });
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + 70, y: y + 20 }] });
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  expect((await canvas.screenshot()).equals(before)).toBe(false);
  await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x - 30, y, id: 0 }, { x: x + 30, y, id: 1 }] });
  await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - 60, y, id: 0 }, { x: x + 60, y, id: 1 }] });
  await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await expect(page.getByText('100%', { exact: true })).toHaveCount(0);
  await page.screenshot({ path: '/tmp/roomvision-mobile.png', fullPage: true });
  await context.close();
});
